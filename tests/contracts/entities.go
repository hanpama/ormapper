package contracts

type simpleAuto struct {
	ID            int64 `agg:"auto"`
	Name          string
	Nullable      *string
	AutoGenerated int `agg:"auto"`
}

type simpleUUID struct {
	ID            string `agg:"primary"`
	Name          string
	Nullable      *string
	AutoGenerated int `agg:"auto"`
}

type composite struct {
	Key1     int `agg:"primary"`
	Key2     int `agg:"primary"`
	Name     string
	Nullable *string
}

type specialQuote struct {
	ID   int64  `agg:"auto"`
	Name string `agg:"column:select"`
}

type order struct {
	ID         int64 `agg:"auto"`
	CustomerID int64
	Total      float64
	Note       *orderNote
	Items      []*orderItem
}

type orderItem struct {
	ID      int64 `agg:"auto"`
	OrderID int64 `agg:"parental"`
	Name    string
	Qty     int
	Lots    []*orderItemLot
}

type orderItemLot struct {
	ID          int64 `agg:"auto"`
	OrderItemID int64 `agg:"parental"`
	Code        string
}

type orderNote struct {
	ID      int64 `agg:"auto"`
	OrderID int64 `agg:"parental"`
	Body    string
}

type identifyingRoot struct {
	ID     int64 `agg:"auto"`
	Name   string
	Detail *identifyingDetail
}

type identifyingDetail struct {
	RootID int64 `agg:"primary,parental"`
	Body   string
}
