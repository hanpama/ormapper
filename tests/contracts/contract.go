func seedOrders(t *testing.T, ctx context.Context, m *ormapper.Mapper, db *sql.DB) []*order {
	t.Helper()

	orders := []*order{
		{CustomerID: 42, Total: 50, Items: []*orderItem{{Name: "alpha", Qty: 1}, {Name: "beta", Qty: 2}}},
		{CustomerID: 43, Total: 10, Items: []*orderItem{{Name: "gamma", Qty: 3}}},
		{CustomerID: 44, Total: 75, Items: []*orderItem{{Name: "delta", Qty: 4}, {Name: "epsilon", Qty: 5}, {Name: "zeta", Qty: 6}}},
	}
	for _, order := range orders {
		if err := m.Save(ctx, db, order); err != nil {
			t.Fatalf("seed order: %v", err)
		}
	}
	return orders
}

