func strPtr(s string) *string {
	return &s
}

func reset(t *testing.T, f Fixture) context.Context {
	t.Helper()

	ctx := context.Background()
	f.ResetSchema(t, ctx, f.DB)
	return ctx
}

func mapperFor(dialect ormapper.Dialect) *ormapper.Mapper {
	return ormapper.MustCompile(
		dialect,
		ormapper.Map(&simpleAuto{}, ormapper.WithTable("simple_auto")),
		ormapper.Map(&simpleUUID{}, ormapper.WithTable("simple_uuid")),
		ormapper.Map(&composite{}, ormapper.WithTable("composite")),
		ormapper.Map(&specialQuote{}, ormapper.WithTable("special quote")),
		ormapper.Map(&order{}, ormapper.WithTable("orders")),
		ormapper.Map(&orderItem{}, ormapper.WithTable("order_items")),
		ormapper.Map(&orderItemLot{}, ormapper.WithTable("order_item_lots")),
		ormapper.Map(&orderNote{}, ormapper.WithTable("order_notes")),
		ormapper.Map(&identifyingRoot{}, ormapper.WithTable("identifying_roots")),
		ormapper.Map(&identifyingDetail{}, ormapper.WithTable("identifying_details")),
	)
}

func countRows(t *testing.T, ctx context.Context, db *sql.DB, query string, args ...any) int64 {
	t.Helper()

	var count int64
	if err := db.QueryRowContext(ctx, query, args...).Scan(&count); err != nil {
		t.Fatalf("count rows: %v", err)
	}
	return count
}

func assertMissing[T any](t *testing.T, ctx context.Context, m *ormapper.Mapper, db ormapper.DBTX, id ormapper.Key) {
	t.Helper()

	var found *T
	if err := m.Get(ctx, db, &found, id); err != nil {
		t.Fatalf("Get missing: %v", err)
	}
	if found != nil {
		t.Fatalf("expected missing row, got %#v", found)
	}
}

func runSimpleAuto(t *testing.T, f Fixture) {
	ctx := reset(t, f)
	m := mapperFor(f.Dialect)

	entity := &simpleAuto{
		Name:     "created",
		Nullable: strPtr("nullable"),
	}
	if err := m.Save(ctx, f.DB, entity); err != nil {
		t.Fatalf("Save insert: %v", err)
	}
	if entity.ID == 0 {
		t.Fatal("expected auto ID to be backfilled")
	}
	if entity.AutoGenerated != 42 {
		t.Fatalf("expected auto-generated field 42, got %d", entity.AutoGenerated)
	}

	entity.Name = "updated"
	entity.Nullable = strPtr("changed")
	if err := m.Save(ctx, f.DB, entity); err != nil {
		t.Fatalf("Save update: %v", err)
	}

	var loaded *simpleAuto
	if err := m.Get(ctx, f.DB, &loaded, ormapper.NewKey(entity.ID)); err != nil {
		t.Fatalf("Get: %v", err)
	}
	if loaded == nil {
		t.Fatal("expected entity to load")
	}
	if loaded.Name != "updated" {
		t.Fatalf("expected updated name, got %q", loaded.Name)
	}
	if loaded.Nullable == nil || *loaded.Nullable != "changed" {
		t.Fatalf("expected nullable value to round-trip, got %#v", loaded.Nullable)
	}
	if loaded.AutoGenerated != 42 {
		t.Fatalf("expected auto-generated field to remain 42, got %d", loaded.AutoGenerated)
	}
	if countRows(t, ctx, f.DB, "SELECT COUNT(*) FROM simple_auto WHERE id = "+f.Placeholder(1), entity.ID) != 1 {
		t.Fatal("Save of existing entity inserted a duplicate row")
	}

	stale := &simpleAuto{
		ID:       1000,
		Name:     "stale generated id",
		Nullable: strPtr("should fail"),
	}
	if err := m.Save(ctx, f.DB, stale); !errors.Is(err, ormapper.ErrStaleEntity) {
		t.Fatalf("expected stale generated entity error, got %v", err)
	}
}

func runBulkMapper(t *testing.T, f Fixture) {
	ctx := reset(t, f)
	m := mapperFor(f.Dialect)

	first := &simpleAuto{Name: "bulk-first"}
	second := &simpleAuto{Name: "bulk-second"}
	if err := m.SaveMany(ctx, f.DB, []*simpleAuto{first, second}); err != nil {
		t.Fatalf("SaveMany insert: %v", err)
	}
	if first.ID == 0 || second.ID == 0 || first.ID == second.ID {
		t.Fatalf("expected distinct generated IDs, got first=%d second=%d", first.ID, second.ID)
	}

	var loaded []*simpleAuto
	ids := []ormapper.Key{
		ormapper.NewKey(second.ID),
		ormapper.NewKey(int64(999999)),
		ormapper.NewKey(first.ID),
	}
	if err := m.GetMany(ctx, f.DB, &loaded, ids); err != nil {
		t.Fatalf("GetMany: %v", err)
	}
	if len(loaded) != len(ids) {
		t.Fatalf("expected %d loaded slots, got %d", len(ids), len(loaded))
	}
	if loaded[0] == nil || loaded[0].ID != second.ID || loaded[0].Name != "bulk-second" {
		t.Fatalf("expected second entity in first slot, got %#v", loaded[0])
	}
	if loaded[1] != nil {
		t.Fatalf("expected missing entity slot to be nil, got %#v", loaded[1])
	}
	if loaded[2] == nil || loaded[2].ID != first.ID || loaded[2].Name != "bulk-first" {
		t.Fatalf("expected first entity in third slot, got %#v", loaded[2])
	}

	first.Name = "bulk-first-updated"
	second.Name = "bulk-second-updated"
	if err := m.SaveMany(ctx, f.DB, []*simpleAuto{first, second}); err != nil {
		t.Fatalf("SaveMany update: %v", err)
	}

	loaded = nil
	if err := m.GetMany(ctx, f.DB, &loaded, []ormapper.Key{ormapper.NewKey(first.ID), ormapper.NewKey(second.ID)}); err != nil {
		t.Fatalf("GetMany after update: %v", err)
	}
	if loaded[0] == nil || loaded[0].Name != "bulk-first-updated" {
		t.Fatalf("expected first update, got %#v", loaded[0])
	}
	if loaded[1] == nil || loaded[1].Name != "bulk-second-updated" {
		t.Fatalf("expected second update, got %#v", loaded[1])
	}

	if err := m.DeleteMany(ctx, f.DB, []*simpleAuto{{ID: first.ID}, {ID: second.ID}}); err != nil {
		t.Fatalf("DeleteMany: %v", err)
	}
	if countRows(t, ctx, f.DB, "SELECT COUNT(*) FROM simple_auto WHERE id IN ("+f.Placeholder(1)+", "+f.Placeholder(2)+")", first.ID, second.ID) != 0 {
		t.Fatal("expected DeleteMany to remove both rows")
	}

	var empty []*simpleAuto
	if err := m.GetMany(ctx, f.DB, &empty, nil); err != nil {
		t.Fatalf("GetMany empty: %v", err)
	}
	if len(empty) != 0 {
		t.Fatalf("expected empty GetMany result, got %d", len(empty))
	}
	if err := m.SaveMany(ctx, f.DB, []*simpleAuto{}); err != nil {
		t.Fatalf("SaveMany empty: %v", err)
	}
	if err := m.DeleteMany(ctx, f.DB, []*simpleAuto{}); err != nil {
		t.Fatalf("DeleteMany empty: %v", err)
	}
}

func runGeneratedAutoKeyNotReused(t *testing.T, f Fixture) {
	ctx := reset(t, f)
	m := mapperFor(f.Dialect)

	first := &simpleAuto{Name: "first"}
	if err := m.Save(ctx, f.DB, first); err != nil {
		t.Fatalf("Save first generated entity: %v", err)
	}
	if err := m.Delete(ctx, f.DB, first); err != nil {
		t.Fatalf("Delete first generated entity: %v", err)
	}

	second := &simpleAuto{Name: "second"}
	if err := m.Save(ctx, f.DB, second); err != nil {
		t.Fatalf("Save second generated entity: %v", err)
	}
	if second.ID <= first.ID {
		t.Fatalf("generated key was reused or moved backwards: first=%d second=%d", first.ID, second.ID)
	}
}

