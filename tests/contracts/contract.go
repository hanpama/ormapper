	all, err := ormapper.NewQuery[order](m, f.DB, "o").
		OrderBy(ormapper.NewQuery[order](m, f.DB, "o").Asc("o.total")).
		FetchAll(ctx)
	if err != nil {
		t.Fatalf("FetchAll: %v", err)
	}
	if len(all) != 3 {
		t.Fatalf("expected 3 orders, got %d", len(all))
	}

