func runAggregateSave(t *testing.T, f Fixture) {
	ctx := reset(t, f)
	m := mapperFor(f.Dialect)

	root := &order{
		CustomerID: 42,
		Total:      100,
		Note:       &orderNote{Body: "initial note"},
		Items: []*orderItem{
			{Name: "apple", Qty: 1, Lots: []*orderItemLot{{Code: "A1"}}},
			{Name: "pear", Qty: 2, Lots: []*orderItemLot{{Code: "P1"}}},
		},
	}

	if err := m.Save(ctx, f.DB, root); err != nil {
		t.Fatalf("Save aggregate insert: %v", err)
	}
	if root.ID == 0 || root.Note.ID == 0 || root.Items[0].ID == 0 || root.Items[0].Lots[0].ID == 0 {
		t.Fatalf("expected generated IDs to be backfilled: %#v", root)
	}
	if root.Items[0].OrderID != root.ID || root.Items[0].Lots[0].OrderItemID != root.Items[0].ID {
		t.Fatalf("expected parental keys to be injected: %#v", root)
	}

	removedItemID := root.Items[0].ID
	removedLotID := root.Items[0].Lots[0].ID
	root.Total = 125
	root.Note.Body = "updated note"
	root.Items[1].Qty = 5
	root.Items[1].Lots = append(root.Items[1].Lots, &orderItemLot{Code: "P2"})
	root.Items = []*orderItem{
		root.Items[1],
		{Name: "orange", Qty: 3, Lots: []*orderItemLot{{Code: "O1"}}},
	}

	if err := m.Save(ctx, f.DB, root); err != nil {
		t.Fatalf("Save aggregate update: %v", err)
	}

	if countRows(t, ctx, f.DB, "SELECT COUNT(*) FROM order_items WHERE id = "+f.Placeholder(1), removedItemID) != 0 {
		t.Fatal("Save should delete child omitted from aggregate snapshot")
	}
	if countRows(t, ctx, f.DB, "SELECT COUNT(*) FROM order_item_lots WHERE id = "+f.Placeholder(1), removedLotID) != 0 {
		t.Fatal("Save should delete grandchildren of omitted child")
	}

	var loaded *order
	if err := m.Get(ctx, f.DB, &loaded, ormapper.NewKey(root.ID)); err != nil {
		t.Fatalf("Get aggregate: %v", err)
	}
	if loaded == nil || loaded.Total != 125 || loaded.Note == nil || loaded.Note.Body != "updated note" {
		t.Fatalf("unexpected aggregate root/note: %#v", loaded)
	}
	if len(loaded.Items) != 2 {
		t.Fatalf("expected 2 items after replacement save, got %#v", loaded.Items)
	}
	for _, item := range loaded.Items {
		if item.OrderID != loaded.ID {
			t.Fatalf("child parental key mismatch: %#v", item)
		}
		for _, lot := range item.Lots {
			if lot.OrderItemID != item.ID {
				t.Fatalf("grandchild parental key mismatch: %#v", lot)
			}
		}
	}
}

